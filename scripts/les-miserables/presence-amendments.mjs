export function amendPresence(chapter, row) {
  // The guard remains at the station throughout 52:1–78. The soldiers
  // handle Fantine at 14–20, she addresses them at 31–37, and Javert
  // explicitly addresses the sergeant again at 41. Only Javert exits at 71.
  const stationGuard = {
    15: 'Remains with the station guard as the mayor interrupts the soldiers and orders Fantine released.',
    26: 'Stays at the station while Fantine addresses the soldiers and approaches the door believing herself free.',
    73: 'Remains on duty with the station detachment after Javert leaves, as the mayor promises help and Fantine faints.',
  }
  if (chapter === 52 && Object.hasOwn(stationGuard, row.at)) return {
    ...row, present: [...row.present, ['montreuil-guard-sergeant', stationGuard[row.at]]],
  }
  const amendment = presenceAmendments.find(([number, at]) => number === chapter && at === row.at)
  const amended = amendment ? { ...row, kind: 'scene', present: amendment[2],
    mentioned: (row.mentioned ?? []).filter(key => !amendment[2].some(([actor]) => actor === key)),
  } : row
  // Chapter 221 paragraphs 42–47 handcuff the couple. Neither leaves before
  // Javert names the other prisoners at 48–63; do not lose them at that cut.
  if (chapter === 221 && row.at === 48) return { ...amended, present:[...amended.present,
    ['thenardier', 'Is handcuffed and down on the floor after sheltering behind his wife; Javert now reviews the other captives.'],
    ['madame-thenardier', 'Has been handcuffed after throwing the paving-stone and crying for her daughters; she remains with the arrested party.'],
  ] }
  if (chapter===107 && row.at===7) return {...amended,present:[...amended.present,
    ['valjean','Saws firewood in his shirt-sleeves in the corridor while the old woman examines the coat indoors.'],
    ['cosette','Watches the wood being sawed outside the room while the old woman searches the hanging coat.'],
  ]}
  return amended
}

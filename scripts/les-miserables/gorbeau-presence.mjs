export function projectGorbeauPresence(chapter,row) {
  const extra = [...(gorbeauCastAdditions.find(([n,at])=>n===chapter&&at===row.at)?.[2] ?? [])]
  const observer=chapter===220?ambushObserverStates.find(state=>state.at===row.at):null
  if(observer)extra.push(['marius',observer.note])
  const present = row.present.filter(([key])=>!['attic-first-blackened-entrant','attic-second-blackened-entrant'].includes(key))
  for(const pair of extra) {
    if(present.some(([key])=>key===pair[0])) throw Error(`Duplicate Gorbeau addition ${chapter}/${row.at}/${pair[0]}`)
    present.push(pair)
  }
  const reveals = gorbeauIdentityEvidence.filter(f=>f.chapter===chapter&&f.at===row.at)
    .map(({chapter:ignoredChapter,at:ignoredAt,...fact})=>fact)
  return {...row,present,
    ...(chapter===219&&row.at===11?{
      description:'Two unidentified men enter silently while Jondrette offers the painted panel. The visitor begins to question their presence.',
      unidentifiedParticipants:{count:2,evidenceParagraphs:[11,20],reason:'Transient indistinguishable arrivals; no unsupported individual identity match.'},
    }:{}),
    ...(chapter===219&&row.at===29?{items:[...(row.items??[]),'jondrette-turned-wooden-panel']}:{}),
    ...(reveals.length?{identityReveals:[...(row.identityReveals??[]),...reveals]}:{}),
    mentioned:(row.mentioned??[]).filter(key=>!present.some(([actor])=>actor===key)),
  }
}
